# Loop subdivision of the WebXR generic hand (MIT, Amazon) with skin weights, writes a C header.
import sys, struct, numpy as np
from pygltflib import GLTF2
g=GLTF2().load(sys.argv[1]); blob=g.binary_blob()
def acc(i):
    a=g.accessors[i]; bv=g.bufferViews[a.bufferView]
    comp={5126:('f',4),5123:('H',2),5125:('I',4),5121:('B',1)}[a.componentType]
    n={'SCALAR':1,'VEC2':2,'VEC3':3,'VEC4':4,'MAT4':16}[a.type]
    off=(bv.byteOffset or 0)+(a.byteOffset or 0); stride=bv.byteStride or comp[1]*n
    return np.array([struct.unpack_from('<'+comp[0]*n,blob,off+k*stride) for k in range(a.count)])
p=g.meshes[0].primitives[0]
P=acc(p.attributes.POSITION).astype(float); J=acc(p.attributes.JOINTS_0).astype(int); W=acc(p.attributes.WEIGHTS_0).astype(float); T=acc(p.indices).ravel().reshape(-1,3)
NJ=len(g.skins[0].joints)
# dense weights
S=np.zeros((len(P),NJ))
for i in range(len(P)):
    for k in range(4): S[i,J[i,k]]+=W[i,k]
# weld duplicate positions (uv seams) so subdivision is smooth across seams
key={}; remap=np.zeros(len(P),int); NP=[]; NS=[]
for i,v in enumerate(P):
    k=tuple(np.round(v,6))
    if k not in key: key[k]=len(NP); NP.append(v); NS.append(S[i])
    remap[i]=key[k]
P=np.array(NP); S=np.array(NS); T=remap[T]
T=T[(T[:,0]!=T[:,1])&(T[:,1]!=T[:,2])&(T[:,0]!=T[:,2])]
print('welded',len(P),'tris',len(T))
def loop(P,S,T):
    edges={}; 
    def ek(a,b): return (a,b) if a<b else (b,a)
    for t in T:
        for a,b,c in ((t[0],t[1],t[2]),(t[1],t[2],t[0]),(t[2],t[0],t[1])):
            edges.setdefault(ek(a,b),[]).append(c)
    nb=[set() for _ in P]; bnd=[[] for _ in P]
    for (a,b),opp in edges.items():
        nb[a].add(b); nb[b].add(a)
        if len(opp)==1: bnd[a].append(b); bnd[b].append(a)
    X=np.hstack([P,S])
    NX=np.zeros_like(X)
    for i in range(len(P)):
        if bnd[i]:
            if len(bnd[i])==2: NX[i]=0.75*X[i]+0.125*(X[bnd[i][0]]+X[bnd[i][1]])
            else: NX[i]=X[i]
        else:
            n=len(nb[i]); beta=(5/8-(3/8+np.cos(2*np.pi/n)/4)**2)/n
            NX[i]=(1-n*beta)*X[i]+beta*sum(X[j] for j in nb[i])
    eidx={}; E=[]
    for (a,b),opp in edges.items():
        if len(opp)==2: v=0.375*(X[a]+X[b])+0.125*(X[opp[0]]+X[opp[1]])
        else: v=0.5*(X[a]+X[b])
        eidx[(a,b)]=len(P)+len(E); E.append(v)
    NX=np.vstack([NX,np.array(E)])
    NT=[]
    for t in T:
        a,b,c=t; ab=eidx[ek(a,b)]; bc=eidx[ek(b,c)]; ca=eidx[ek(c,a)]
        NT+= [(a,ab,ca),(ab,b,bc),(ca,bc,c),(ab,bc,ca)]
    return NX[:,:3],NX[:,3:],np.array(NT)
levels=int(sys.argv[3]) if len(sys.argv)>3 else 2
for _ in range(levels): P,S,T=loop(P,S,T)
print('subdivided',len(P),'tris',len(T))
# smooth normals (area weighted)
Nn=np.zeros_like(P)
fn=np.cross(P[T[:,1]]-P[T[:,0]],P[T[:,2]]-P[T[:,0]])
for k in range(3): np.add.at(Nn,T[:,k],fn)
Nn/=np.linalg.norm(Nn,axis=1,keepdims=True)+1e-12
# check winding: normals should point away from the joint skeleton centroid
c=P.mean(0); 
if np.mean(np.sum((P-c)*Nn,1))<0: Nn=-Nn; T=T[:,[0,2,1]]
# glove materials: back = black leather, palm = dark suede, knuckle guard = grey, cuff seam
names=[g.nodes[j].name for j in g.skins[0].joints]
jp={g.nodes[j].name:np.array(g.nodes[j].translation) for j in g.skins[0].joints}
col=np.zeros((len(P),4))
for i,v in enumerate(P):
    c=np.array([0.075,0.075,0.08,0.55])
    if Nn[i,0]<-0.35: c=np.array([0.13,0.115,0.10,0.18])          # palm side (suede)
    for f in ['index','middle','ring','pinky']:
        k=jp[f+'-finger-phalanx-proximal']
        if np.linalg.norm(v-k)<0.017 and Nn[i,0]>0.3: c=np.array([0.20,0.20,0.21,0.35])   # knuckle guard
        k2=jp[f+'-finger-phalanx-intermediate']
        if np.linalg.norm(v-k2)<0.009 and Nn[i,0]>0.3: c=np.array([0.16,0.16,0.17,0.3])
    if v[1]>0.035: c=np.array([0.11,0.11,0.115,0.25])              # wrist band
    col[i]=c
# keep 4 largest weights
JJ=np.argsort(-S,axis=1)[:,:4]; WW=np.take_along_axis(S,JJ,1); WW/=WW.sum(1,keepdims=True)
# rest joints (global TRS, armature is identity)
joints=[]
for j in g.skins[0].joints:
    n=g.nodes[j]; joints.append((n.name,n.translation,n.rotation))
IB=acc(g.skins[0].inverseBindMatrices)
with open(sys.argv[2],'w') as f:
    f.write('// Generated by tools/hand/subdiv.py from the WebXR Input Profiles generic hand (right.glb, MIT License, Copyright (c) 2019 Amazon).\n#pragma once\n')
    f.write('static const int c_hmJoints = %d, c_hmVerts = %d, c_hmTris = %d;\n'%(len(joints),len(P),len(T)))
    f.write('static const char* const c_hmJointNames[%d] = {%s};\n'%(len(joints),','.join('"%s"'%n for n,_,_ in joints)))
    f.write('// rest pose: translation xyz, rotation quaternion xyzw (model space)\nstatic const float c_hmRest[%d][7] = {\n'%len(joints))
    for n,t,r in joints: f.write('{%s},\n'%','.join('%.7ff'%x for x in list(t)+list(r)))
    f.write('};\nstatic const float c_hmPos[%d] = {\n'%(len(P)*3))
    for v in P: f.write('%.6ff,%.6ff,%.6ff,\n'%tuple(v))
    f.write('};\nstatic const float c_hmNrm[%d] = {\n'%(len(P)*3))
    for v in Nn: f.write('%.4ff,%.4ff,%.4ff,\n'%tuple(v))
    f.write('};\nstatic const float c_hmCol[%d] = {\n'%(len(P)*4))
    for v in col: f.write('%.3ff,%.3ff,%.3ff,%.3ff,\n'%tuple(v))
    f.write('};\nstatic const unsigned char c_hmJ[%d] = {\n'%(len(P)*4))
    for j in JJ: f.write('%d,%d,%d,%d,\n'%tuple(j))
    f.write('};\nstatic const float c_hmW[%d] = {\n'%(len(P)*4))
    for w in WW: f.write('%.4ff,%.4ff,%.4ff,%.4ff,\n'%tuple(w))
    f.write('};\nstatic const unsigned short c_hmIdx[%d] = {\n'%(len(T)*3))
    for t in T: f.write('%d,%d,%d,\n'%tuple(t))
    f.write('};\n')
